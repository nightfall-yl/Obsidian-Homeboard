import esbuild from "esbuild";
import { cp, mkdir, readFile, writeFile } from "fs/promises";
import process from "process";
import builtins from "builtin-modules";
import sveltePlugin from "esbuild-svelte";
import sveltePreprocess from "svelte-preprocess";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the plugin source
*/
`;

const prod = process.argv[2] === "production";

async function syncManifestVersion() {
	const packageJson = JSON.parse(await readFile("package.json", "utf8"));
	const manifestJson = JSON.parse(await readFile("manifest.json", "utf8"));
	manifestJson.version = packageJson.version;
	await writeFile("manifest.json", JSON.stringify(manifestJson, null, 2));
	console.log(`Synced manifest.json version → ${packageJson.version}`);
}

async function updateVersionsJson() {
	const packageJson = JSON.parse(await readFile("package.json", "utf8"));
	const currentVersion = packageJson.version;

	// 从 manifest.json 读取 minAppVersion 作为权威来源
	const manifestJson = JSON.parse(await readFile("manifest.json", "utf8"));
	const minObsidianVersion = manifestJson.minAppVersion;

	let versionsJson;
	try {
		versionsJson = JSON.parse(await readFile("versions.json", "utf8"));
	} catch {
		versionsJson = {};
	}

	versionsJson[currentVersion] = minObsidianVersion;

	const sortedVersions = Object.fromEntries(
		Object.entries(versionsJson).sort(([a], [b]) => {
			const aParts = a.split(".").map(Number);
			const bParts = b.split(".").map(Number);
			for (let i = 0; i < Math.max(aParts.length, bParts.length); i++) {
				const aVal = aParts[i] || 0;
				const bVal = bParts[i] || 0;
				if (aVal !== bVal) {
					return bVal - aVal;
				}
			}
			return 0;
		})
	);

	await writeFile("versions.json", JSON.stringify(sortedVersions, null, 2));
	console.log(`Updated versions.json: added version ${currentVersion} with min Obsidian version ${minObsidianVersion}`);
}

async function copyPluginFilesToDist() {
	const distDir = "dist";
	const files = ["main.js", "manifest.json", "styles.css"];

	await mkdir(distDir, { recursive: true });
	await Promise.all(
		files.map((file) => cp(file, `${distDir}/${file}`))
	);
	console.log(`Copied plugin files to ${distDir}/`);
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: false,
	outfile: "main.js",
	minify: prod,
	loader: {
		".css": "text",
	},
	plugins: [
		sveltePlugin({
			preprocess: sveltePreprocess(),
			compilerOptions: {
				css: true,
			},
		}),
	],
	mainFields: ["svelte", "browser", "module", "main"],
});

if (prod) {
	await context.rebuild();
	await syncManifestVersion();
	await updateVersionsJson();
	await copyPluginFilesToDist();
	process.exit(0);
} else {
	await context.watch();
}
